-- 1. ENUMS
DO $$ BEGIN
    CREATE TYPE user_role AS ENUM (
        'Enseignant',
        'Etudiant',
        'Secretaire',
        'SuperAdmin',
        'DirecteurDepartement',
        'DirecteurEtablissement'
    );
EXCEPTION WHEN duplicate_object THEN null; END $$;

DO $$ BEGIN
    CREATE TYPE type_seance AS ENUM ('COURS', 'TD', 'TP');
EXCEPTION WHEN duplicate_object THEN null; END $$;

DO $$ BEGIN
    CREATE TYPE type_salle AS ENUM ('COURS', 'TP');
EXCEPTION WHEN duplicate_object THEN null; END $$;

DO $$ BEGIN
    CREATE TYPE jour AS ENUM ('LUNDI', 'MARDI', 'MERCREDI', 'JEUDI', 'VENDREDI', 'SAMEDI');
EXCEPTION WHEN duplicate_object THEN null; END $$;

-- 2. PROFILES TABLE (Linked with auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nom TEXT NOT NULL DEFAULT '',
    prenom TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL,
    role user_role NOT NULL DEFAULT 'Etudiant',
    photo TEXT DEFAULT '',
    matricule TEXT,
    date_inscription DATE DEFAULT CURRENT_DATE,
    grade TEXT,
    specialite TEXT,
    bureau TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. ACADEMIC STRUCTURE TABLES
CREATE TABLE IF NOT EXISTS public.departements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    code TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    niveau TEXT NOT NULL,
    effectif INT DEFAULT 0,
    departement_id BIGINT REFERENCES public.departements(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.salles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero TEXT NOT NULL UNIQUE,
    capacite INT NOT NULL DEFAULT 30,
    type type_salle NOT NULL DEFAULT 'COURS',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.matieres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    intitule TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.seances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jour jour NOT NULL,
    heure_debut TIME NOT NULL,
    heure_fin TIME NOT NULL,
    type type_seance NOT NULL DEFAULT 'COURS',
    color_variant TEXT DEFAULT 'blue',
    matiere_id BIGINT REFERENCES public.matieres(id) ON DELETE CASCADE,
    salle_id BIGINT REFERENCES public.salles(id) ON DELETE SET NULL,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    enseignant_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.absences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    motif TEXT DEFAULT '',
    justifiee BOOLEAN DEFAULT false,
    etudiant_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    seance_id BIGINT REFERENCES public.seances(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.voeux (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enseignant_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    annee_universitaire TEXT NOT NULL,
    semestre TEXT NOT NULL,
    statut TEXT NOT NULL DEFAULT 'EN_ATTENTE',
    date_depot TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.voeux_matieres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voeu_id BIGINT REFERENCES public.voeux(id) ON DELETE CASCADE,
    matiere_id BIGINT REFERENCES public.matieres(id) ON DELETE CASCADE,
    priorite INT DEFAULT 1,
    type_seance type_seance NOT NULL DEFAULT 'COURS',
    volume_horaire NUMERIC(5,2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

