-- Schema Expansion: Tables for Groupes TP, Inscriptions, Notes, Offres Enseignement, Voeux Emploi
-- Execute this script in your Supabase Dashboard -> SQL Editor
-- ==============================================================================

-- 1. GROUPES TP (Safe creation with soft-link so it works even if classes is not yet created)
CREATE TABLE IF NOT EXISTS public.groupes_tp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    capacite INT NOT NULL DEFAULT 15,
    classe_id BIGINT,
    classe_nom TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Add foreign key constraint safely only if public.classes exists
DO $$ BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'classes'
    ) THEN
        IF NOT EXISTS (
            SELECT 1 FROM information_schema.table_constraints 
            WHERE constraint_name = 'fk_groupes_tp_classe'
        ) THEN
            ALTER TABLE public.groupes_tp 
            ADD CONSTRAINT fk_groupes_tp_classe 
            FOREIGN KEY (classe_id) REFERENCES public.classes(id) ON DELETE CASCADE;
        END IF;
    END IF;
END $$;

-- 2. CAMPAGNES D'INSCRIPTION
CREATE TABLE IF NOT EXISTS public.inscriptions_campagnes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annee TEXT NOT NULL UNIQUE,
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL,
    statut TEXT NOT NULL DEFAULT 'Ouverte',
    inscrits INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. NOTES ACADÉMIQUES
CREATE TABLE IF NOT EXISTS public.notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etudiant_id UUID,
    etudiant_nom TEXT,
    matricule TEXT,
    matiere TEXT NOT NULL,
    note NUMERIC(4, 2) NOT NULL,
    coefficient NUMERIC(3, 1) DEFAULT 1.0,
    semestre TEXT DEFAULT 'S1',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. OFFRES D'ENSEIGNEMENT
CREATE TABLE IF NOT EXISTS public.offres_enseignement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departement_id BIGINT,
    matiere TEXT NOT NULL,
    semestre TEXT NOT NULL DEFAULT 'S1',
    volume_cours INT DEFAULT 21,
    volume_td INT DEFAULT 21,
    volume_tp INT DEFAULT 21,
    places_ouvertes INT DEFAULT 1,
    places_assignees INT DEFAULT 0,
    statut TEXT DEFAULT 'Ouverte aux vœux',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. VOEUX EMPLOI DU TEMPS (Étudiants / Enseignants)
CREATE TABLE IF NOT EXISTS public.voeux_emploi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    user_nom TEXT,
    jour TEXT NOT NULL,
    heure_debut TEXT NOT NULL,
    heure_fin TEXT NOT NULL,
    disponible BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Active RLS and allow read/write for all users
ALTER TABLE public.groupes_tp ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inscriptions_campagnes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.offres_enseignement ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.voeux_emploi ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    CREATE POLICY "Allow all for groupes_tp" ON public.groupes_tp FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY "Allow all for inscriptions_campagnes" ON public.inscriptions_campagnes FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY "Allow all for notes" ON public.notes FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY "Allow all for offres_enseignement" ON public.offres_enseignement FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY "Allow all for voeux_emploi" ON public.voeux_emploi FOR ALL USING (true) WITH CHECK (true);
EXCEPTION WHEN duplicate_object THEN null; END $$;

